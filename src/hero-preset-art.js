import { drawMedievalHero } from "./medieval-hero-art.js";
import { drawBloodHero } from "./blood-hero-art.js";
// Use the original heroes' canvas primitives, ink and proportions.
export function drawHeroPreset(g, type, { shape, rounded, ellipse, line, ink }) {
  if (drawBloodHero(g, type, { shape, rounded, ellipse, line, ink })) return;
  if (drawMedievalHero(g, type, { shape, rounded, ellipse, line, ink })) return;
  const poly = (points, fill, width = 5) => shape(g, points, fill, ink, width);
  const mark = (points, color = ink, width = 4) => line(g, points, color, width);
  const face = (x = 43, y = 48, w = 42, h = 33) => {
    rounded(g, x, y, w, h, 8, "#eadbb6", ink, 4);
    mark([[x + 11, y + 12], [x + 11, y + 18]]);
    mark([[x + w - 11, y + 12], [x + w - 11, y + 18]]);
  };
  const robe = (color, wide = false) => poly([[42, 71], [wide ? 25 : 33, 100], [wide ? 100 : 90, 100], [84, 71]], color);
  const gem = (x, y, color = "#e8c77d") => poly([[x, y - 6], [x + 5, y], [x, y + 6], [x - 5, y]], color, 3);
  if (type === "ironwarden") {
    robe("#879a91", true);
    poly([[28, 73], [42, 70], [45, 92], [22, 95]], "#a7b8aa");
    poly([[83, 70], [101, 74], [106, 96], [82, 91]], "#a7b8aa");
    poly([[37, 40], [48, 27], [79, 27], [92, 41], [90, 77], [64, 86], [38, 77]], "#aabbb3");
    poly([[39, 52], [88, 52], [85, 69], [64, 76], [43, 68]], "#364e46", 4);
    mark([[54, 58], [54, 65]], "#efe4b5", 4); mark([[75, 58], [75, 65]], "#efe4b5", 4);
    mark([[64, 32], [64, 48]], "#e3e0c4", 4);
    poly([[52, 87], [76, 87], [72, 103], [56, 103]], "#627c6d", 3);
    gem(64, 89);
  } else if (type === "shellguard") {
    poly([[29, 96], [18, 76], [25, 45], [43, 36], [88, 35], [107, 52], [110, 82], [96, 103]], "#6d895b");
    mark([[22, 70], [34, 65], [42, 83], [32, 97]], "#3f5942", 4);
    mark([[103, 53], [92, 65], [96, 86], [108, 81]], "#3f5942", 4);
    robe("#a5ae70");
    poly([[35, 44], [43, 26], [78, 23], [91, 38], [94, 67], [37, 68]], "#93ac76");
    poly([[44, 34], [67, 28], [80, 39], [68, 47], [46, 46]], "#bac88e", 3);
    face(41, 51, 46, 33);
    rounded(g, 46, 84, 35, 19, 6, "#cfbb7d", ink, 4);
    mark([[50, 93], [76, 93]], "#9b8f58", 3);
  } else if (type === "emberblade") {
    robe("#9a654a", true);
    poly([[28, 76], [42, 73], [45, 89], [24, 94]], "#9ca18b");
    poly([[83, 74], [98, 77], [104, 95], [81, 90]], "#9ca18b");
    face(42, 49, 44, 35);
    poly([[31, 56], [35, 37], [46, 40], [44, 21], [61, 32], [70, 17], [77, 33], [91, 27], [93, 45], [102, 55], [80, 52], [67, 43], [54, 56]], "#b76d4e");
    mark([[42, 56], [82, 56]], "#e3bb77", 5);
    mark([[77, 68], [80, 74]], "#9f654e", 2.5);
    poly([[41, 84], [52, 81], [87, 97], [83, 105]], "#d4b785", 3);
    ellipse(g, 66, 93, 4, 4, "#516551");
  } else if (type === "ronin") {
    robe("#6b8275");
    poly([[81, 75], [105, 79], [99, 86], [110, 92], [87, 90]], "#aa775c", 4);
    face(44, 49, 41, 32);
    poly([[23, 51], [60, 23], [70, 23], [104, 53], [91, 62], [33, 62]], "#ceb987");
    mark([[63, 29], [63, 53]], "#9c875c", 3);
    mark([[53, 35], [40, 53]], "#9c875c", 3); mark([[75, 36], [88, 53]], "#9c875c", 3);
    rounded(g, 42, 77, 43, 11, 3, "#b78062", ink, 4);
    mark([[52, 91], [45, 100]], "#a7b7a0", 3);
  } else if (type === "falconer") {
    robe("#75835b");
    poly([[81, 49], [86, 24], [101, 14], [103, 32], [91, 49]], "#e0d8b3", 4);
    mark([[88, 44], [98, 24]], "#91a68c", 3);
    poly([[29, 54], [43, 32], [75, 26], [92, 48], [92, 76], [36, 78]], "#698c6b");
    face(42, 48, 43, 32);
    poly([[29, 53], [45, 34], [73, 28], [91, 50], [65, 44], [44, 57]], "#8fa77b");
    poly([[40, 80], [53, 79], [84, 99], [76, 104]], "#c0a274", 3);
    rounded(g, 51, 91, 11, 11, 2, "#dbc68b", ink, 3);
  } else if (type === "gunner") {
    robe("#9a7b54", true);
    face(42, 47, 44, 35);
    poly([[32, 50], [37, 31], [49, 25], [81, 25], [95, 40], [96, 57]], "#b18c5e");
    rounded(g, 34, 39, 59, 14, 5, "#775a44", ink, 4);
    rounded(g, 39, 37, 21, 21, 8, "#a9c4b6", ink, 4);
    rounded(g, 67, 37, 21, 21, 8, "#a9c4b6", ink, 4);
    mark([[45, 44], [51, 41]], "#edf0cd", 3); mark([[73, 44], [79, 41]], "#edf0cd", 3);
    poly([[62, 73], [53, 71], [47, 77], [58, 79], [65, 76], [72, 79], [84, 75], [77, 71]], "#6f5b41", 3);
    mark([[63, 86], [63, 101]], "#d4bd86", 4);
    ellipse(g, 77, 92, 3, 3, "#edcd86");
  } else if (type === "raven") {
    poly([[41, 65], [25, 101], [45, 97], [56, 108], [69, 98], [94, 103], [87, 68]], "#686278");
    poly([[28, 57], [38, 34], [65, 20], [88, 32], [99, 60], [87, 85], [39, 84]], "#686a83");
    poly([[41, 52], [62, 41], [84, 52], [87, 69], [66, 79], [41, 70]], "#303f40", 4);
    mark([[50, 57], [55, 59]], "#d8dbb1", 4); mark([[73, 59], [79, 56]], "#d8dbb1", 4);
    poly([[43, 65], [66, 69], [85, 63], [77, 79], [64, 89], [49, 80]], "#a3a6ad", 4);
    mark([[64, 73], [64, 83]], "#647475", 3);
    gem(64, 95, "#aab7ae");
  } else if (type === "foxblade") {
    poly([[85, 88], [96, 69], [109, 66], [108, 85], [101, 104], [79, 104]], "#b77753");
    poly([[99, 80], [108, 67], [107, 87], [100, 94]], "#ebdabb", 3);
    robe("#987257");
    poly([[29, 58], [31, 24], [52, 36], [71, 34], [94, 22], [95, 51], [102, 64], [90, 81], [36, 80]], "#bd805b");
    poly([[37, 33], [40, 47], [50, 42]], "#e6c79d", 2.5);
    poly([[79, 42], [89, 31], [89, 47]], "#e6c79d", 2.5);
    poly([[36, 56], [53, 53], [65, 62], [78, 53], [94, 56], [86, 75], [66, 86], [44, 75]], "#eddfbc", 4);
    mark([[48, 63], [54, 65]], ink, 4); mark([[76, 65], [82, 62]], ink, 4);
    poly([[61, 75], [69, 75], [65, 79]], "#4c5442", 2);
    rounded(g, 43, 84, 43, 10, 3, "#799385", ink, 3);
  } else if (type === "frostwitch") {
    robe("#78a4aa");
    poly([[32, 64], [36, 39], [52, 31], [80, 32], [94, 48], [94, 84], [77, 91], [40, 84]], "#c1d4cf");
    face(44, 49, 40, 34);
    poly([[36, 52], [48, 37], [80, 39], [91, 58], [76, 54], [67, 65], [59, 53], [43, 62]], "#dae0cc", 4);
    poly([[44, 37], [42, 22], [57, 31], [65, 16], [73, 31], [87, 23], [84, 42], [63, 46]], "#9ccbd0", 4);
    mark([[64, 25], [64, 37]], "#edf0d0", 3);
    poly([[41, 84], [65, 96], [86, 83], [81, 99], [48, 101]], "#b4cfc3", 3);
    gem(65, 89, "#e8dc9c");
  } else if (type === "antler") {
    const left = [[48, 43], [37, 32], [32, 14], [34, 26], [23, 24], [19, 16]];
    const right = [[80, 43], [91, 32], [96, 14], [94, 26], [105, 24], [110, 16]];
    for (const branch of [left, right]) { mark(branch, ink, 9); mark(branch, "#b0a07a", 4); }
    robe("#769364", true);
    poly([[34, 59], [41, 39], [65, 31], [87, 39], [95, 64], [84, 87], [39, 84]], "#8fa879");
    face(44, 50, 41, 33);
    poly([[35, 55], [46, 38], [62, 34], [56, 51], [44, 61]], "#b5c18a", 3);
    poly([[65, 35], [84, 41], [91, 56], [76, 54]], "#a5bb87", 3);
    poly([[41, 81], [56, 85], [64, 103], [45, 96]], "#bdc593", 3);
    poly([[84, 81], [71, 85], [64, 103], [85, 97]], "#a2b879", 3);
    gem(65, 85, "#d1a571");
  }
}
