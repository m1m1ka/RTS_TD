import assert from "node:assert/strict";
import { Game } from "../src/game.js";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
import { enterShop, sellableCards, sellShopCard, cardSellPrice } from "../src/shop.js";
import { migrateEconomy } from "../src/economy.js";
const c = structuredClone(DEFAULT_CONFIG);
c.initial.cards = {hero_blue:2, hero_green:1, hero_purple:1, fireball:3, coin_purse:2};
c.cards.hero_blue.rarity="common";c.cards.hero_green.rarity="rare";c.cards.hero_purple.rarity="epic";
Object.assign(c.initial.economy,{commonHeroSellPrice:2,rareHeroSellPrice:5,epicHeroSellPrice:9,battleSellPrice:3,resourceSellPrice:4,equipmentSellPrice:6});
const g=new Game(()=>{},c);
assert.equal(sellShopCard(g,"hero_blue"),false);
assert.ok(g.playCard("hero_blue",2,3));
const hero=g.heroes[0];hero.level=7;hero.equipment=["guard"];
g.heroes=[];g.heroReserve=[hero];g.cards.hero_blue=2;
enterShop(g);
assert.deepEqual(["hero_blue","hero_green","hero_purple","fireball","coin_purse"].map(k=>cardSellPrice(g,k)),[2,5,9,3,4]);
let gold=g.gold;
assert.ok(sellShopCard(g,"hero_blue"));assert.equal(g.gold,gold+2);
assert.equal(g.heroReserve[0],hero,"selling fresh copy preserves trained hero");
assert.equal(sellShopCard(g,"hero_blue"),false,"trained copy must be selected explicitly");
assert.ok(sellShopCard(g,"hero_blue",`reserve-${hero.id}`));
assert.equal(g.heroReserve.length,0);assert.equal(g.cards.hero_blue,undefined);
assert.equal(sellShopCard(g,"hero_blue",`reserve-${hero.id}`),false);
const copies=g.syncSkillCards().filter(s=>s.cardId==="fireball");
copies[0].tier=2;copies[0].readyAt=99;copies[1].readyAt=55;
assert.ok(sellShopCard(g,"fireball",copies[0].id));
assert.equal(g.cards.fireball,2);assert.ok(!g.skillCards.some(s=>s.id===copies[0].id));
assert.equal(g.skillCards.find(s=>s.id===copies[1].id).readyAt,55);
assert.equal(sellShopCard(g,"fireball",copies[0].id),false);
g.shop.opening={};gold=g.gold;
assert.equal(sellShopCard(g,"coin_purse"),false);assert.equal(g.gold,gold);
g.shop.opening=null;assert.ok(sellShopCard(g,"coin_purse"));assert.equal(g.cards.coin_purse,1);
g.config.initial.economy.resourceSellPrice=0;gold=g.gold;assert.ok(sellShopCard(g,"coin_purse"));assert.equal(g.gold,gold);
const equipment=Object.keys(c.cards).find(k=>c.cards[k].category==="equipment");
g.cards[equipment]=1;gold=g.gold;assert.ok(sellShopCard(g,equipment));assert.equal(g.gold,gold+6);
assert.ok(sellableCards(g).every(r=>r.count>0));
delete c.initial.economy.battleSellPrice;migrateEconomy(c);
assert.equal(c.initial.economy.battleSellPrice,1);assert.equal(c.initial.economy.epicHeroSellPrice,9);
const combat=new Game(()=>{},c);
combat.playCard("hero_blue",2,3);combat.playCard("hero_green",4,3);combat.select(0);
combat.heroes[0].triggerRules=[];combat.hit(combat.heroes[0],100000);
assert.equal(combat.selectedUnit(),undefined);assert.equal(combat.selected,-1);
combat.select(1);assert.equal(combat.selectedUnit(),combat.heroes[1]);
combat.heroes[1].hp=0;assert.equal(combat.selectedUnit(),undefined,"other death paths cannot leave a controllable corpse");
console.log("PASS sales and selection: rarity/category prices, exact skill/reserve removal, cooldown preservation, invalid sales, migration and dead selection");
