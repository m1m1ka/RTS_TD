import assert from "node:assert/strict";
import { Game } from "../src/game.js";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
import { debugGenerateCard, debugLevelHero } from "../src/debug-actions.js";
const c=structuredClone(DEFAULT_CONFIG);
c.cards.hero_blue.effects=[];c.cards.hero_blue.triggerRules=[];
const g=new Game(()=>{},c), saved=JSON.stringify(g.config);
assert.equal(debugGenerateCard(g,"missing",1),false);
assert.equal(debugGenerateCard(g,"hero_blue",.5),false);
assert.equal(debugGenerateCard(g,"hero_blue",100),false);
const before=g.cards.fireball||0;
assert.ok(debugGenerateCard(g,"fireball",3));assert.equal(g.cards.fireball,before+3);
assert.equal(g.skillCards.filter(c=>c.cardId==="fireball").length,before+3);
assert.equal(debugLevelHero(g,999,1),false);
assert.ok(g.playCard("hero_blue",7,3));
const h=g.heroes[0];h.hp=h.maxHp/2;
assert.ok(debugLevelHero(g,h.id,4));assert.equal(h.level,5);assert.equal(h.rank,1);
assert.equal(h.hp,h.maxHp/2);
assert.ok(debugLevelHero(g,h.id,10));assert.equal(h.rank,3);
h.hp=0;assert.ok(debugLevelHero(g,h.id,1));assert.equal(h.hp,0,"debug levels do not revive dead heroes");
assert.equal(debugLevelHero(g,h.id,-1),false);
assert.equal(debugLevelHero(g,h.id,1000),false);
assert.equal(JSON.stringify(g.config),saved);
console.log("PASS debug actions: specific card copies, bounds, deployed hero leveling/ranks, health/death and configuration isolation");
