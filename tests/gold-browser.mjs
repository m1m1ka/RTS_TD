import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdirSync } from "node:fs";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
const c = structuredClone(DEFAULT_CONFIG);
c.days = c.days.slice(0, 1); c.days[0].waves = [c.days[0].waves[0]];
c.days[0].mines = [{ x: 5, y: 4, maxHp: 180 }, { x: 9, y: 4, maxHp: 180 }];
c.days[0].waves[0].spawns = [{ x: 7, y: 0, delay: 0, interval: 1, enemies: [{ type: "grunt", count: 1, level: 1 }] }];
c.initial.firstWaveDelay = 0; c.enemies.grunt.maxHp = 1; c.cards.hero_blue.unit.range = 24;
c.cards.hero_blue.unit.critChance = 100;
const server = spawn(process.execPath, ["node_modules/vite/bin/vite.js", "--host", "127.0.0.1", "--port", "5178", "--strictPort"], { stdio: "ignore", windowsHide: true });
let browser;
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch("http://127.0.0.1:5178")).ok) break; } catch {} await new Promise(r => setTimeout(r, 200)); }
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--enable-unsafe-swiftshader"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on("pageerror", e => errors.push(e.message));
  await page.addInitScript(config => localStorage.setItem("friday-defense-config-v1", JSON.stringify(config)), c);
  await page.goto("http://127.0.0.1:5178");
  await page.waitForFunction(() => window.__game?.snapshot().frames > 5);
  const state = () => page.evaluate(() => window.__game.snapshot());
  const advance = n => page.evaluate(seconds => window.__game.advance(seconds), n);
  assert.equal((await state()).mines.length, 2);
  await page.locator('[data-card="hero_blue"]').click();
  await page.evaluate(() => window.__game.clickCell(7, 3));
  await page.evaluate(() => window.__game.clickCell(7, 3));
  assert.equal(await page.locator("#unit-crit").textContent(), "100%");
  await page.locator("#start").click();
  await page.waitForFunction(() => window.__game.snapshot().phase === "victory");
  await page.locator("#pause").click();
  const time = (await state()).settlement.elapsed;
  await page.waitForTimeout(160);
  assert.equal((await state()).settlement.elapsed, time);
  assert.equal(await page.locator("#reward-dialog").isVisible(), false);
  await advance(Math.max(0, 1 - time));
  mkdirSync("logs", { recursive: true });
  await page.screenshot({ path: "logs/victory-confetti.png" });
  await advance(2.2);
  assert.equal((await state()).gold, 4);
  await page.waitForFunction(() => document.querySelector("#gold-total").textContent === "4");
  await page.screenshot({ path: "logs/victory-core-coins.png" });
  await advance(1.1); assert.equal((await state()).gold, 8);
  await page.screenshot({ path: "logs/victory-mine-coins.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "logs/victory-mobile.png" });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await advance(2); assert.equal((await state()).phase, "reward");
  await page.locator('[data-reward="0"]').click();
  await page.locator('[data-reward="1"]').click();
  await page.locator("[data-reward-confirm]").click();
  await page.waitForFunction(() => window.__game.snapshot().phase !== "reward");
  assert.equal((await state()).phase, "won"); assert.equal((await state()).gold, 8);
  assert.deepEqual(errors, []);
  console.log("PASS gold browser: mines, victory/confetti, pause, sequential vertical coins, HUD totals, mobile and delayed rewards");
} finally { await browser?.close(); server.kill(); }
