import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdirSync } from "node:fs";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
import { SHOP_DEFAULTS } from "../src/shop.js";

const url = "http://127.0.0.1:5201", config = structuredClone(DEFAULT_CONFIG);
config.initial.cards = { hero_blue: 1, fireball: 3, coffee: 2 };
config.initial.firstWaveDelay = 0; config.initial.boatSpeed = 20;
config.cards.fireball.cooldown = 6;
for (const card of Object.values(config.cards)) if (card.category === "hero") card.triggerRules = [];
config.days[0].obstacles = []; config.days[0].mines = [];
config.days[0].waves = [{ id: "wave_1", name: "技能测试", startDelay: 0, hpScale: 1, atkScale: 1,
  spawns: [{ x: 0, y: 5, delay: 0, interval: 100, enemies: [{ type: "grunt", count: 1 }] }] }];
config.enemies.grunt.maxHp = 100000; config.enemies.grunt.speed = .1;
const server = spawn(process.execPath, ["node_modules/vite/bin/vite.js", "--host", "127.0.0.1", "--port", "5201", "--strictPort"],
  { stdio: "ignore", windowsHide: true, env: { ...process.env, FRIDAY_CONFIG_SYNC: "0" } });
let browser;
try {
  for (let i = 0; i < 60; i++) { try { if ((await fetch(url)).ok) break; } catch {} await new Promise(r => setTimeout(r, 200)); }
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true, args: ["--enable-unsafe-swiftshader"] });
  const errors = [], context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  context.setDefaultTimeout(15000);
  await context.addInitScript(c => { if (!localStorage.getItem("friday-defense-config-v1")) localStorage.setItem("friday-defense-config-v1", JSON.stringify(c)); }, config);
  const page = await context.newPage(); page.on("pageerror", e => errors.push(e.message));
  await page.goto(url); await page.waitForFunction(() => window.__game?.snapshot().frames > 3);
  const snap = () => page.evaluate(() => window.__game.snapshot());
  const skills = page.locator('#hand [data-card="fireball"]');
  assert.equal(await skills.count(), 3); assert.equal(await skills.locator(".card-count").count(), 0);
  assert.equal(await page.locator('[data-card="coffee"] .card-count').innerText(), "×2");
  await page.locator('[data-card="hero_blue"]').click(); await page.evaluate(() => window.__game.clickCell(7, 3));
  await page.locator("#start").click(); await page.locator("#pause").click(); await page.evaluate(() => window.__game.advance(1));
  const enemy = (await snap()).enemies[0]; assert.ok(enemy && !enemy.boatId);
  await page.locator("#pause").click(); await skills.nth(1).click();
  await page.evaluate(p => { window.__game.clickCell(p.x, p.y); document.querySelector("#pause").click(); }, enemy);
  let state = await snap(); assert.equal(state.cards.fireball, 3);
  assert.equal(state.skillCards.filter(c => c.remaining > 0).length, 1);
  assert.ok(await skills.nth(1).isDisabled()); assert.ok(await skills.nth(0).isEnabled());
  const remaining = state.skillCards[1].remaining;
  await page.waitForTimeout(200); assert.equal((await snap()).skillCards[1].remaining, remaining, "pause freezes cooldown");
  await page.locator("#pause").click();
  const box = await skills.nth(2).boundingBox(), aim = await page.evaluate(p => window.__game.cellToScreen(p.x, p.y), enemy);
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(aim.x, aim.y, { steps: 12 }); await page.mouse.up(); await page.locator("#pause").click();
  assert.equal((await snap()).skillCards.filter(c => c.remaining > 0).length, 2, "drag consumes the selected copy's availability");
  mkdirSync("logs", { recursive: true }); await page.screenshot({ path: "logs/skills-cooldown.png" });
  await page.evaluate(() => window.__game.advance(6.1));
  assert.equal(await skills.locator('.skill-cooldown:not([hidden])').count(), 0);
  assert.ok(await skills.nth(1).isEnabled());
  const editor = await context.newPage(); editor.on("pageerror", e => errors.push(e.message));
  await editor.goto(url + "/config.html"); await editor.locator('[data-category="battle"]').click();
  await editor.locator('[data-select="fireball"]').click();
  assert.equal(await editor.locator("#card-preview .card-count").count(), 0);
  await editor.locator('[data-path="cards.fireball.cooldown"]').fill("7");
  await editor.locator('[data-path="cards.fireball.skillTiers.0.cooldown"]').fill("4");
  await editor.locator('[data-path="cards.fireball.skillTiers.0.effects.0.value"]').fill("999");
  await editor.locator('[data-action="add-skill-tier"]').click();
  assert.equal(await editor.locator('[data-path="cards.fireball.skillTiers.2.cooldown"]').count(), 1);
  await editor.locator('[data-action="remove-skill-tier"]').click();
  await editor.locator('[data-effect-choice="cards.fireball.skillTiers.0"]').selectOption("slow");
  await editor.locator('[data-action="add-effect"][data-effect-owner="cards.fireball.skillTiers.0"]').click();
  await editor.locator('[data-path="cards.fireball.skillTiers.0.effects.1.duration"]').fill("8");
  await editor.locator("#save-config").click();
  await page.waitForFunction(() => document.querySelector('[data-card="fireball"] .card-kind').textContent.includes("CD 7"));
  const saved = await editor.evaluate(() => JSON.parse(localStorage.getItem("friday-defense-config-v1")));
  assert.equal(saved.cards.fireball.skillTiers[0].effects[0].value, 999);
  assert.equal(saved.cards.fireball.skillTiers[0].effects[1].duration, 8);
  await editor.reload(); await editor.locator('[data-category="battle"]').click(); await editor.locator('[data-select="fireball"]').click();
  assert.equal(await editor.locator('[data-path="cards.fireball.skillTiers.0.effects.0.value"]').inputValue(), "999");
  await editor.locator('[data-path="cards.fireball.skillTiers.0.cooldown"]').scrollIntoViewIfNeeded();
  await editor.screenshot({ path: "logs/skills-config.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await skills.nth(2).scrollIntoViewIfNeeded(); await page.screenshot({ path: "logs/skills-hand-mobile.png" });

  const shopConfig = structuredClone(saved);
  shopConfig.initial.cards.fireball = 9;
  const shopDay = shopConfig.days[0]; shopDay.kind = "shop"; shopDay.shop = { ...SHOP_DEFAULTS }; shopDay.waves = [];
  const shopContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await shopContext.addInitScript(c => localStorage.setItem("friday-defense-config-v1", JSON.stringify(c)), shopConfig);
  const shop = await shopContext.newPage(); shop.on("pageerror", e => errors.push(e.message));
  await shop.goto(url);
  await shop.waitForFunction(() => window.__game?.snapshot().phase === "shop", null, { timeout: 10000 }).catch(async error => { console.log(errors, await shop.evaluate(() => ({ phase: window.__game?.snapshot().phase, body: document.body.innerText.slice(-1000) }))); throw error; });
  await shop.locator('[data-skill-fuse="fireball"][data-tier="1"]').scrollIntoViewIfNeeded();
  assert.match(await shop.locator(".fusion-recipe").first().innerText(), /999/);
  for (let i = 0; i < 3; i++) await shop.locator('[data-skill-fuse="fireball"][data-tier="1"]').click();
  assert.equal((await shop.evaluate(() => window.__game.snapshot())).cards.fireball, 3);
  assert.equal(await shop.locator('#hand [data-card="fireball"]').count(), 3);
  assert.match(await shop.locator('#hand [data-card="fireball"] .card-kind').first().innerText(), /2 阶/);
  await shop.waitForTimeout(600);
  await shop.screenshot({ path: "logs/skills-fusion.png" });
  await shop.locator('[data-skill-fuse="fireball"][data-tier="2"]').click();
  assert.equal((await shop.evaluate(() => window.__game.snapshot())).cards.fireball, 1);
  assert.ok(await shop.locator('[data-skill-fuse="fireball"][data-tier="3"]').isDisabled());
  await shop.setViewportSize({ width: 390, height: 844 });
  await shop.locator(".skill-forge").scrollIntoViewIfNeeded();
  assert.ok(await shop.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await shop.screenshot({ path: "logs/skills-fusion-mobile.png" });
  assert.ok(await shop.locator("#shop-dialog").evaluate(e => e.scrollWidth <= e.clientWidth + 1));
  await shop.screenshot({ path: "logs/skills-fusion-mobile.png" });
  assert.deepEqual(errors, []);
  console.log("PASS skills browser: independent hand cards, click/drag cooldown, paused timer, readiness, tier effects editor and persistence, live save, three-to-one shop fusion, tier limits and mobile layouts");
} finally { await browser?.close(); server.kill(); }
