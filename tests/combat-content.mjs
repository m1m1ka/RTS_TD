import assert from "node:assert/strict";
import { Game } from "../src/game.js";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
import { assertConfig } from "../src/config/schema.js";
import { cardPlayRules } from "../src/config/trigger-rules.js";
import { migrateCombatContent } from "../src/combat-content.js";
import { getWeaponSpec } from "../src/weapons.js";
const c=structuredClone(DEFAULT_CONFIG);
c.days[0].obstacles=[];c.days[0].mines=[];
c.cards.hero_blue.effects=[];c.cards.hero_blue.triggerRules=[];
c.initial.cards={hero_blue:1,coffee:2,arcane:1};
assertConfig(c);
assert.equal(c.cards.coffee.category,"battle");
assert.equal(c.cards.coffee.skillTiers[0].effects[0].value,360);
assert.equal(c.cards.coffee.skillTiers[1].effects[0].value,1080);
const g=new Game(()=>{},c);g.playCard("hero_blue",7,3);const h=g.heroes[0];
assert.equal(g.playCard("coffee",7,3),false,"full health consumes neither cooldown nor card");
g.syncSkillCards();const [first,second]=g.skillCards.filter(s=>s.cardId==="coffee");
h.hp-=150;assert.ok(g.playCard("coffee",7,3,first.id));
assert.equal(h.hp,h.maxHp-30);assert.equal(g.cards.coffee,2);
assert.equal(g.playCard("coffee",7,3,first.id),false);
assert.ok(first.readyAt>g.time);assert.equal(second.readyAt,0);
const hot=structuredClone(c);hot.cards.hero_blue.triggerRules=[structuredClone(cardPlayRules.battleCooldown)];
hot.cards.hero_blue.triggerRules[0].effects[0].chance=100;g.applyConfig(hot);
h.hp-=100;assert.ok(g.playCard("coffee",7,3,second.id));
assert.equal(second.readyAt,g.time);assert.ok(first.readyAt>g.time,"reset only the used copy");
assert.equal(g.cards.coffee,2);
hot.cards.hero_blue.triggerRules[0].effects[0].chance=0;g.applyConfig(hot);
h.hp-=100;assert.ok(g.playCard("coffee",7,3,second.id));assert.ok(second.readyAt>g.time);
const weapon=h.weapon,range=h.range;assert.ok(g.playCard("arcane",7,3));
assert.equal(h.weapon,weapon);assert.equal(h.range,range);assert.equal(h.splash,.55);
assert.equal(getWeaponSpec({weapon:"staff"})?.splash,0);
const followers=g.summonFollowers(h,{count:8,hpPercent:50,atkPercent:50});
assert.equal(followers.length,8);assert.equal(new Set(followers.map(f=>`${f.x},${f.y}`)).size,8);
assert.equal(g.summonFollowers(h,{count:8,hpPercent:50,atkPercent:50}).length,0);
followers[0].hp=0;assert.equal(g.summonFollowers(h,{count:1,hpPercent:50,atkPercent:50}).length,1);
const old=structuredClone(c);delete old.combatContentVersion;
old.cards.coffee.category="resource";delete old.cards.coffee.skillTiers;
old.cards.arcane.effects=[{type:"weapon",weapon:"staff",range:3},{type:"stat",stat:"atk",mode:"add",value:9}];
migrateCombatContent(old);assert.equal(old.cards.coffee.category,"battle");
assert.equal(old.cards.arcane.effects[1].value,9);assert.ok(!old.cards.arcane.effects.some(e=>e.type==="weapon"));
const bad=structuredClone(hot);bad.cards.hero_blue.triggerRules[0].effects[0].chance=101;
assert.throws(()=>assertConfig(bad));
console.log("PASS combat content: reusable healing/tiers, exact-copy cooldown reset, zero/full chance, unchanged equipment weapon, no default orb splash, eight followers and migration");
