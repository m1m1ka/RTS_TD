import assert from "node:assert/strict";
import { Game } from "../src/game.js";
import { DEFAULT_CONFIG } from "../src/config/defaults.js";
import { newTriggerRule } from "../src/config/trigger-rules.js";
import { changeLevel, applyResourceEffect } from "../src/resource-effects.js";

const c = structuredClone(DEFAULT_CONFIG);
c.days.forEach(d => { d.obstacles = []; d.mines = []; });
c.days[1].kind = "shop";
for (const card of Object.values(c.cards)) if (card.category === "hero") card.triggerRules = [];
c.cards.hero_blue.triggerRules = [{ ...newTriggerRule(), trigger: { event: "preparation", scope: "any", radius: -1 }, effects: [{ type: "level", value: 1 }] }];
c.initial.cards.hero_blue = 2;
const events = [], g = new Game(e => events.push(e), c);
g.playCard("hero_blue", 3, 3); g.playCard("hero_green", 5, 3); g.playCard("hero_purple", 9, 3);
const [a, b, destroyed] = g.heroes;
g.playCard("guard", 3, 3); changeLevel(g, a, 10);
a.triggerPermanentEffects.push({ type: "stat", stat: "atk", mode: "add", value: 7, duration: "permanent" });
a.dayEffects.push({ type: "stat", stat: "speed", mode: "add", value: 2, duration: "day" });
g.rebuildHero(a); a.hp = 20; b.hp = 0;
g.summonFollowers(a, { count: 1, hpPercent: 50, atkPercent: 50 });
applyResourceEffect(g, destroyed, { type: "sacrifice", radius: -1 });
const level = a.level, rank = a.rank, equipment = [...a.equipment], buffs = structuredClone(a.triggerPermanentEffects);
g.phase = "route"; assert.ok(g.chooseDay(g.nextDays()[0]));
assert.equal(g.phase, "shop"); assert.equal(g.heroes.length, 0); assert.equal(g.followers.length, 0);
assert.deepEqual(g.heroReserve, [a, b]); assert.equal(g.cards.hero_blue, 2); assert.equal(g.cards.hero_green, 1);
assert.ok(!g.cards.hero_purple, "permanently destroyed heroes never return");
for (const h of [a, b]) { assert.equal(h.hp, h.maxHp); assert.deepEqual(h.dayEffects, []); assert.deepEqual(h.path, []); }
assert.equal(a.level, level); assert.equal(a.rank, rank); assert.deepEqual(a.equipment, equipment); assert.deepEqual(a.triggerPermanentEffects, buffs);
const cards = structuredClone(g.cards);
g.leaveShop(); assert.ok(g.chooseDay(g.nextDays()[0]));
assert.equal(g.heroes.length, 0); assert.deepEqual(g.cards, cards, "passing through a shop never duplicates returned cards");
assert.equal(g.startDay(), false, "cannot start next battle until a hero is deployed");
assert.equal(events.filter(e => e.type === "heroPreparation").length, 1, "no preparation while in reserve");
assert.ok(g.playCard(a.cardId, 10, 7)); assert.equal(g.heroes[0], a); assert.equal(a.x, 10); assert.equal(a.y, 7);
assert.equal(a.level, level + 1, "new-day deployment runs preparation exactly once");
assert.deepEqual(a.equipment, equipment); assert.deepEqual(a.triggerPermanentEffects, buffs);
assert.equal(g.cards.hero_blue, 1); assert.deepEqual(g.heroReserve, [b]);
assert.ok(g.playCard(a.cardId, a.x, a.y)); assert.equal(a.level, level + 4, "spare copies still upgrade the redeployed hero by three levels");
assert.equal(events.filter(e => e.type === "heroPreparation").length, 2);
g.startDay(); const location = { x: a.x, y: a.y }; g.waitForWave(1);
assert.equal(g.heroes[0], a); assert.deepEqual({ x: a.x, y: a.y }, location, "wave transitions do not recall heroes");
assert.equal(g.heroReserve[0], b, "undeployed heroes can remain in hand");
console.log("PASS daily deployment: living/dead recall, one returned card, shop roundtrip, persistent identity/levels/ranks/equipment/buffs, recovery, destruction, followers, manual placement, preparation once, duplicate upgrades and wave preservation");
